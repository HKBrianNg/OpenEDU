// 有个地方绕不开 React：错误提示可能在组件外拼，所以留一个模块级当前语言。
// Provider 每次渲染都会同步它，两者一致。
let current = 'zh';

export function getCurrentLocale() {
  return current;
}

export function setCurrentLocale(locale) {
  if (TABLES[locale]) current = locale;
}

export function tableFor(locale) {
  return TABLES[locale] ?? TABLES.zh;
}

/** 非组件里也能用（模块级语言跟着 Provider 走） */
export function t(key) {
  return TABLES[current][key] ?? key;
}

export default t;
